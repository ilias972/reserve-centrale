#!/usr/bin/env python3
"""Build the small application SVG sprite from a pinned Lucide Static archive."""

import argparse
import hashlib
import json
import tarfile
import xml.etree.ElementTree as ET
from pathlib import Path

VERSION = "1.61.0"
ARCHIVE_SHA256 = "62773cd2ee411ad2e37c1973d1e4c4b49f9a6c57da6b5d5d0abca08756ba75f1"
ICONS = (
    ("package", "package"),
    ("users", "users"),
    ("building", "building"),
    ("shield", "shield-check"),
    ("sliders", "sliders-horizontal"),
    ("truck", "truck"),
    ("history", "history"),
    ("clipboard", "clipboard-list"),
    ("boxes", "boxes"),
    ("activity", "activity"),
    ("logout", "log-out"),
    ("menu", "menu"),
    ("chevron", "chevron-right"),
    ("back", "arrow-left"),
    ("search", "search"),
    ("plus", "plus"),
    ("basket", "shopping-basket"),
    ("trash", "trash"),
    ("flag", "flag"),
    ("layers", "layers"),
    ("checklist", "clipboard-check"),
    ("image", "image"),
    ("warning", "triangle-alert"),
    ("bell", "bell"),
)
SVG_NS = "http://www.w3.org/2000/svg"
ET.register_namespace("", SVG_NS)
ALLOWED_ELEMENTS = {"path", "rect", "circle", "ellipse", "line", "polyline", "polygon"}
ALLOWED_ATTRIBUTES = {
    "d",
    "x",
    "y",
    "x1",
    "y1",
    "x2",
    "y2",
    "cx",
    "cy",
    "r",
    "rx",
    "ry",
    "width",
    "height",
    "points",
}


def source_svg(archive: tarfile.TarFile, name: str) -> bytes:
    member = archive.extractfile(f"package/icons/{name}.svg")
    if member is None:
        raise ValueError(f"Pinned package is missing icon {name!r}")
    return member.read()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path, help="lucide-static-1.61.0.tgz")
    args = parser.parse_args()
    raw = args.archive.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != ARCHIVE_SHA256:
        raise SystemExit("Refusing an unverified Lucide archive.")

    root = Path(__file__).resolve().parents[1]
    symbols = []
    with tarfile.open(args.archive, "r:gz") as archive:
        manifest_file = archive.extractfile("package/package.json")
        license_file = archive.extractfile("package/LICENSE")
        if manifest_file is None or license_file is None:
            raise SystemExit("Pinned archive is missing package metadata or its license.")
        metadata = json.load(manifest_file)
        if metadata.get("version") != VERSION or metadata.get("license") != "ISC":
            raise SystemExit("Lucide package metadata does not match the pinned release.")
        for alias, name in ICONS:
            # main() verifies the exact archive SHA-256 before parsing this SVG.
            element = ET.fromstring(source_svg(archive, name))  # noqa: S314
            if (
                element.tag.rsplit("}", 1)[-1] != "svg"
                or element.attrib.get("viewBox") != "0 0 24 24"
            ):
                raise SystemExit(f"Unexpected SVG root for {name!r}.")
            symbol = ET.Element(f"{{{SVG_NS}}}symbol", {"id": alias, "viewBox": "0 0 24 24"})
            for child in element:
                tag = child.tag.rsplit("}", 1)[-1]
                if tag not in ALLOWED_ELEMENTS or set(child.attrib) - ALLOWED_ATTRIBUTES:
                    raise SystemExit(f"Unexpected SVG content in {name!r}.")
                ET.SubElement(symbol, f"{{{SVG_NS}}}{tag}", dict(child.attrib))
            symbols.append(symbol)
        sprite = ET.Element(f"{{{SVG_NS}}}svg")
        sprite.append(
            ET.Comment(
                f" Lucide Static {VERSION}; source SHA-256 {digest}; generated by scripts/build_icon_sprite.py. "
            )
        )
        sprite.extend(symbols)
        (root / "static/ui/icons.svg").write_bytes(
            ET.tostring(sprite, encoding="utf-8", xml_declaration=False)
        )
        (root / "static/ui/LUCIDE-LICENSE.txt").write_bytes(license_file.read())
    print(f"Generated {len(ICONS)} Lucide symbols from {VERSION} ({digest}).")


if __name__ == "__main__":
    main()
